#!/usr/bin/env node
// ATLAS milestone tracker — validates docs/FEATURE_TRACKER.md and computes verified progress.
//
//   node scripts/tracker.mjs           validate + print the progress summary
//   node scripts/tracker.mjs --check   also fail if docs/PROJECT_STATUS.md's generated block is stale
//   node scripts/tracker.mjs --write   validate + regenerate the block in docs/PROJECT_STATUS.md
//
// Progress = tasks with status Done ÷ all tracked tasks. Nothing else counts.
// Owner: Claude Code (structure). Both agents run it after editing the tracker.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TRACKER = path.join(root, 'docs', 'FEATURE_TRACKER.md');
const STATUS_DOC = path.join(root, 'docs', 'PROJECT_STATUS.md');
const BEGIN = '<!-- tracker:begin — generated by `node scripts/tracker.mjs --write`; do not edit by hand -->';
const END = '<!-- tracker:end -->';
const STATUSES = ['Backlog', 'Ready', 'In Progress', 'Blocked', 'In Review', 'Done'];
const OWNERS = ['Claude Code', 'Codex', 'Shared'];
const ID_RE = /^[A-Z]{2,4}-\d{2}$/;
const isEmpty = (s) => !s || s === '—' || s === '-';

function parse(text) {
  const milestones = [];
  const tasks = [];
  const errors = [];
  let current = null;
  text.split(/\r?\n/).forEach((line, i) => {
    const n = i + 1;
    const heading = line.match(/^## M(\d+) · (.+?)\s*$/);
    if (heading) {
      current = { num: Number(heading[1]), name: heading[2], tasks: [] };
      milestones.push(current);
      return;
    }
    if (/^#{1,2} /.test(line)) {
      current = null; // any other H1/H2 ends the milestone section
      return;
    }
    if (!/^\|\s*[A-Z]{2,4}-\d{2}\s*\|/.test(line)) return;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length !== 7) {
      errors.push(`line ${n}: expected 7 columns, found ${cells.length} (a "|" inside a cell breaks the table)`);
      return;
    }
    const [id, task, owner, status, deps, criteria, evidence] = cells;
    if (!current) {
      errors.push(`line ${n}: ${id} is outside a "## M<n> · <name>" milestone section`);
      return;
    }
    const t = {
      id, task, owner, status, criteria, evidence, line: n, milestone: current,
      deps: isEmpty(deps) ? [] : deps.split(',').map((d) => d.trim()).filter(Boolean),
    };
    current.tasks.push(t);
    tasks.push(t);
  });
  return { milestones, tasks, errors };
}

function validate({ milestones, tasks, errors }) {
  const warnings = [];
  const byId = new Map();
  for (const t of tasks) {
    const at = `line ${t.line} ${t.id}`;
    if (!ID_RE.test(t.id)) errors.push(`${at}: ID must look like ABC-01`);
    if (byId.has(t.id)) errors.push(`${at}: duplicate ID (first on line ${byId.get(t.id).line})`);
    else byId.set(t.id, t);
    if (isEmpty(t.task)) errors.push(`${at}: empty description`);
    if (!OWNERS.includes(t.owner)) errors.push(`${at}: owner "${t.owner}" must be one of: ${OWNERS.join(', ')}`);
    if (!STATUSES.includes(t.status)) errors.push(`${at}: status "${t.status}" must be one of: ${STATUSES.join(', ')}`);
    if (isEmpty(t.criteria)) errors.push(`${at}: acceptance criteria are required`);
  }
  for (const t of tasks) {
    const at = `line ${t.line} ${t.id}`;
    for (const d of t.deps) {
      if (d === t.id) errors.push(`${at}: depends on itself`);
      else if (!byId.has(d)) errors.push(`${at}: unknown dependency "${d}"`);
    }
    const unmet = t.deps.filter((d) => byId.has(d) && byId.get(d).status !== 'Done');
    if (t.status === 'Done') {
      if (isEmpty(t.evidence)) errors.push(`${at}: Done requires evidence of completion`);
      if (unmet.length) errors.push(`${at}: Done but dependencies are not Done: ${unmet.join(', ')}`);
    }
    if (t.status === 'Ready' && unmet.length) errors.push(`${at}: Ready but dependencies are not Done: ${unmet.join(', ')}`);
    if (t.status === 'Blocked' && !/^Blocker:/i.test(t.evidence)) {
      errors.push(`${at}: Blocked requires the Evidence column to start with "Blocker: <reason>"`);
    }
    if ((t.status === 'In Progress' || t.status === 'In Review') && unmet.length) {
      warnings.push(`${at}: ${t.status} while dependencies are not Done: ${unmet.join(', ')}`);
    }
  }
  // Dependency cycles.
  const state = new Map();
  const visit = (id, trail) => {
    if (state.get(id) === 'done' || !byId.has(id)) return;
    if (state.get(id) === 'active') {
      errors.push(`dependency cycle: ${[...trail.slice(trail.indexOf(id)), id].join(' → ')}`);
      return;
    }
    state.set(id, 'active');
    for (const d of byId.get(id).deps) visit(d, [...trail, id]);
    state.set(id, 'done');
  };
  for (const t of tasks) visit(t.id, []);
  // Milestone structure.
  milestones.forEach((m, i) => {
    if (m.num !== i + 1) warnings.push(`milestone "M${m.num} · ${m.name}" is out of order (expected M${i + 1})`);
    if (m.tasks.length === 0) errors.push(`milestone M${m.num} · ${m.name} has no tasks`);
  });
  if (milestones.length === 0) errors.push('no "## M<n> · <name>" milestone sections found');
  return warnings;
}

const pct = (done, total) => (total ? `${(Math.round((done / total) * 1000) / 10).toFixed(1)}%` : '—');
const count = (list, status) => list.filter((t) => t.status === status).length;

function generate(milestones, tasks) {
  const date = new Date().toISOString().slice(0, 10);
  const done = count(tasks, 'Done');
  const out = [
    BEGIN,
    `_Generated ${date} from \`docs/FEATURE_TRACKER.md\`. Progress = Done tasks ÷ all tracked tasks; drafts, mocks and untested work never count._`,
    '',
    `**Overall verified completion: ${done} of ${tasks.length} tasks (${pct(done, tasks.length)})**`,
    '',
    '| Milestone | Done | Total | Progress | Ready | In Progress | In Review | Blocked | Backlog |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|',
  ];
  for (const m of milestones) {
    const d = count(m.tasks, 'Done');
    out.push(
      `| M${m.num} · ${m.name} | ${d} | ${m.tasks.length} | ${pct(d, m.tasks.length)} | ` +
        ['Ready', 'In Progress', 'In Review', 'Blocked', 'Backlog'].map((s) => count(m.tasks, s)).join(' | ') +
        ' |',
    );
  }
  out.push(
    `| **All** | **${done}** | **${tasks.length}** | **${pct(done, tasks.length)}** | ` +
      ['Ready', 'In Progress', 'In Review', 'Blocked', 'Backlog'].map((s) => `**${count(tasks, s)}**`).join(' | ') +
      ' |',
  );
  const section = (title, statuses, fmt) => {
    const list = tasks.filter((t) => statuses.includes(t.status));
    out.push('', `### ${title}`, '');
    if (list.length === 0) out.push('- None');
    else for (const t of list) out.push(fmt(t));
  };
  section('Blocked', ['Blocked'], (t) => `- **${t.id}** (${t.owner}) ${t.task} — ${t.evidence.replace(/^Blocker:\s*/i, 'blocker: ')}`);
  section('In progress / in review', ['In Progress', 'In Review'], (t) => `- **${t.id}** (${t.owner}, ${t.status}) ${t.task}`);
  section('Ready to start', ['Ready'], (t) => `- **${t.id}** (${t.owner}) ${t.task}`);
  section('Done (verified)', ['Done'], (t) => `- **${t.id}** (${t.owner}) ${t.task}`);
  out.push(END);
  return out.join('\n');
}

const stripDate = (block) => block.replace(/^_Generated \d{4}-\d{2}-\d{2} /m, '_Generated ');

// ---- main ----
const args = new Set(process.argv.slice(2));
if (!fs.existsSync(TRACKER)) {
  console.error(`tracker: ${path.relative(root, TRACKER)} not found`);
  process.exit(1);
}
const parsed = parse(fs.readFileSync(TRACKER, 'utf8'));
const warnings = validate(parsed);
const { milestones, tasks, errors } = parsed;

for (const w of warnings) console.log(`WARN  ${w}`);
for (const e of errors) console.log(`ERROR ${e}`);

const done = count(tasks, 'Done');
console.log(`\nVerified completion: ${done}/${tasks.length} (${pct(done, tasks.length)})`);
for (const m of milestones) {
  const d = count(m.tasks, 'Done');
  console.log(`  M${m.num} ${m.name.padEnd(36)} ${String(d).padStart(2)}/${String(m.tasks.length).padEnd(2)} ${pct(d, m.tasks.length).padStart(6)}`);
}

let failed = errors.length > 0;
if (!failed && (args.has('--write') || args.has('--check'))) {
  const block = generate(milestones, tasks);
  const doc = fs.existsSync(STATUS_DOC) ? fs.readFileSync(STATUS_DOC, 'utf8') : '';
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    console.log(`ERROR docs/PROJECT_STATUS.md must contain the generated-block markers:\n${BEGIN}\n${END}`);
    failed = true;
  } else {
    const existing = doc.slice(start, end + END.length);
    if (args.has('--write')) {
      if (existing !== block) fs.writeFileSync(STATUS_DOC, doc.slice(0, start) + block + doc.slice(end + END.length));
      console.log(existing === block ? 'PROJECT_STATUS.md already current.' : 'PROJECT_STATUS.md regenerated.');
    } else if (stripDate(existing.replace(/\r\n/g, '\n')) !== stripDate(block)) {
      console.log('ERROR docs/PROJECT_STATUS.md generated block is stale — run: node scripts/tracker.mjs --write');
      failed = true;
    }
  }
}
console.log(failed ? '\nTracker: FAIL' : '\nTracker: OK');
process.exit(failed ? 1 : 0);
